import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { RULES } from './definitions.js';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '../../');

function ensureDir(filePath) {
  const dir = path.dirname(filePath);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
}

// -------------------------------------------------------------
// 1. Generate shared/generated/rules.js (GUI / JS)
// -------------------------------------------------------------
function generateJsRules() {
  const target = path.join(rootDir, 'shared/generated/rules.js');
  ensureDir(target);

  const content = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY.
 * Source: shared/rules/definitions.js
 * Generated by: shared/rules/generator.js
 */

export const RULES = ${JSON.stringify(RULES, null, 2)};

export const ASN_REGEX = new RegExp(${JSON.stringify(RULES.asn.regexStr)});
export const PUBLIC_KEY_REGEX = new RegExp(${JSON.stringify(RULES.publicKey.regexStr)});
export const IPV4_REGEX = new RegExp(${JSON.stringify(RULES.ipv4.regexStr)});
export const IPV6_ULA_REGEX = new RegExp(${JSON.stringify(RULES.ipv6Ula.regexStr)});
export const LINK_LOCAL_REGEX = new RegExp(${JSON.stringify(RULES.linkLocal.regexStr)});

export function normalizeAsn(val) {
  if (val === null || val === undefined) return '';
  return String(val).trim().replace(/^AS/i, '');
}

export function calcDefaultPort(asn) {
  const cleanAsn = parseInt(normalizeAsn(asn), 10);
  if (isNaN(cleanAsn) || cleanAsn <= 0) return ${RULES.port.baseOffset + 1};
  return ${RULES.port.baseOffset} + (cleanAsn % ${RULES.port.modulo});
}

export function formatDefaultLinkLocal(asn) {
  const cleanAsn = normalizeAsn(asn);
  return cleanAsn ? \`fe80::\${cleanAsn}\` : 'fe80::1';
}

export function validateAsn(val) {
  const clean = normalizeAsn(val);
  if (!clean) return { valid: false, error: 'ASN is required' };
  if (!ASN_REGEX.test(clean)) return { valid: false, error: ${JSON.stringify(RULES.asn.errorMessage)} };
  const num = parseInt(clean, 10);
  if (num < ${RULES.asn.min} || num > ${RULES.asn.max}) {
    return { valid: false, error: ${JSON.stringify(RULES.asn.errorMessage)} };
  }
  return { valid: true, value: num };
}

export function validatePublicKey(val) {
  if (!val || typeof val !== 'string') return { valid: false, error: 'Public key is required' };
  const trimmed = val.trim();
  if (trimmed.length !== ${RULES.publicKey.length} || !PUBLIC_KEY_REGEX.test(trimmed)) {
    return { valid: false, error: ${JSON.stringify(RULES.publicKey.errorMessage)} };
  }
  return { valid: true, value: trimmed };
}

export function validateIpv4(val, isOptional = false) {
  if (!val || typeof val !== 'string' || !val.trim()) {
    if (isOptional) return { valid: true, value: null };
    return { valid: false, error: 'IPv4 address is required' };
  }
  const trimmed = val.trim();
  if (!IPV4_REGEX.test(trimmed)) {
    return { valid: false, error: ${JSON.stringify(RULES.ipv4.errorMessage)} };
  }
  return { valid: true, value: trimmed };
}

export function validateIpv6Ula(val, isOptional = false) {
  if (!val || typeof val !== 'string' || !val.trim()) {
    if (isOptional) return { valid: true, value: null };
    return { valid: false, error: 'IPv6 ULA is required' };
  }
  const trimmed = val.trim();
  if (!IPV6_ULA_REGEX.test(trimmed)) {
    return { valid: false, error: ${JSON.stringify(RULES.ipv6Ula.errorMessage)} };
  }
  return { valid: true, value: trimmed };
}

export function validateLinkLocal(val) {
  if (!val || typeof val !== 'string') return { valid: false, error: 'Link-Local address is required' };
  const trimmed = val.trim();
  if (!LINK_LOCAL_REGEX.test(trimmed)) {
    return { valid: false, error: ${JSON.stringify(RULES.linkLocal.errorMessage)} };
  }
  return { valid: true, value: trimmed };
}

export function validatePort(val, isOptional = false) {
  if (val === null || val === undefined || val === '' || val === 'auto') {
    if (isOptional || val === 'auto') return { valid: true, value: 'auto' };
    return { valid: false, error: 'Port is required' };
  }
  const num = parseInt(val, 10);
  if (isNaN(num) || num < ${RULES.port.min} || num > ${RULES.port.max}) {
    return { valid: false, error: ${JSON.stringify(RULES.port.errorMessage)} };
  }
  return { valid: true, value: num };
}

export function validateMtu(val) {
  if (val === null || val === undefined || val === '') return { valid: true, value: ${RULES.mtu.default} };
  const num = parseInt(val, 10);
  if (isNaN(num) || num < ${RULES.mtu.min} || num > ${RULES.mtu.max}) {
    return { valid: false, error: ${JSON.stringify(RULES.mtu.errorMessage)} };
  }
  return { valid: true, value: num };
}
`;

  fs.writeFileSync(target, content, 'utf8');
  console.log(`[build:rules] Generated ${target}`);
}

