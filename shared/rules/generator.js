// 2. Generate cli/cli-src/lib/rules.sh (Busybox CLI)
// -------------------------------------------------------------
function generateShellRules() {
  const target = path.join(rootDir, 'cli/cli-src/lib/rules.sh');
  ensureDir(target);

  const content = `#!/bin/sh
# AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY.
# Source: shared/rules/definitions.js
# Generated by: shared/rules/generator.js
#
# Busybox POSIX-compliant helper functions (0-fork, parameter expansion)

normalize_asn() {
  _asn="\${1#[aA][sS]}"
  _asn="\${_asn%% }"
  _asn="\${_asn## }"
  echo "$_asn"
}

calc_default_port() {
  _asn="$(normalize_asn "$1")"
  case "$_asn" in
    ''|*[!0-9]*) echo "${RULES.port.baseOffset + 1}" ;;
    *) echo "$(( ${RULES.port.baseOffset} + (_asn % ${RULES.port.modulo}) ))" ;;
  esac
}

validate_asn() {
  _val="$(normalize_asn "$1")"
  case "$_val" in
    ''|*[!0-9]*) return 1 ;;
  esac
  if [ \${#_val} -gt 10 ] || [ "$_val" -eq 0 ]; then
    return 1
  fi
  return 0
}

validate_pubkey() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  if [ \${#_val} -ne ${RULES.publicKey.length} ]; then
    return 1
  fi
  case "$_val" in
    *=) ;;
    *) return 1 ;;
  esac
  case "$_val" in
    *[!A-Za-z0-9+/=]*) return 1 ;;
  esac
  return 0
}

validate_ipv4() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  [ -z "$_val" ] && return 1
  _ip="\${_val%%/*}"
  case "$_ip" in
    *.*.*.*) ;;
    *) return 1 ;;
  esac
  _o1="\${_ip%%.*}"; _rest="\${_ip#*.}"
  _o2="\${_rest%%.*}"; _rest="\${_rest#*.}"
  _o3="\${_rest%%.*}"; _o4="\${_rest#*.}"
  for _o in "$_o1" "$_o2" "$_o3" "$_o4"; do
    case "$_o" in
      ''|*[!0-9]*) return 1 ;;
    esac
    if [ "$_o" -lt 0 ] || [ "$_o" -gt 255 ]; then
      return 1
    fi
  done
  return 0
}

validate_ipv6_ula() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  [ -z "$_val" ] && return 1
  case "$_val" in
    [fF][dD]*:*) return 0 ;;
    *) return 1 ;;
  esac
}

validate_link_local() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  [ -z "$_val" ] && return 1
  case "$_val" in
    [fF][eE]80:*|[fF][eE]80::*) return 0 ;;
    *) return 1 ;;
  esac
}

validate_port() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  [ "$_val" = "auto" ] && return 0
  case "$_val" in
    ''|*[!0-9]*) return 1 ;;
  esac
  if [ "$_val" -ge ${RULES.port.min} ] && [ "$_val" -le ${RULES.port.max} ]; then
    return 0
  fi
  return 1
}

validate_mtu() {
  _val="$1"
  _val="\${_val%% }"
  _val="\${_val## }"
  [ -z "$_val" ] && return 0
  case "$_val" in
    *[!0-9]*) return 1 ;;
  esac
  if [ "$_val" -ge ${RULES.mtu.min} ] && [ "$_val" -le ${RULES.mtu.max} ]; then
    return 0
  fi
  return 1
}
`;

  fs.writeFileSync(target, content, 'utf8');
  console.log(`[build:rules] Generated ${target}`);
}

